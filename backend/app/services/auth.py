"""Signup and login logic. Routes stay thin and call these."""

import asyncio
import logging

from sqlalchemy import select
from sqlalchemy.exc import IntegrityError
from sqlalchemy.ext.asyncio import AsyncSession

from app.auth.hashing import hash_password, verify_password
from app.auth.tokens import create_access_token
from app.core.config import get_settings
from app.core.exception import EmailAlreadyRegisteredError, InvalidCredentialsError
from app.core.logging import mask_email
from app.models.users import User
from app.schema.auth import LoginRequest, SignupRequest, Token

logger = logging.getLogger(__name__)


async def _get_by_email(db: AsyncSession, email: str) -> User | None:
    result = await db.execute(select(User).where(User.email == email))
    return result.scalar_one_or_none()


async def signup(db: AsyncSession, data: SignupRequest) -> User:
    if await _get_by_email(db, data.email):
        logger.warning(
            "signup_rejected",
            extra={"reason": "email_taken", "email": mask_email(data.email)},
        )
        raise EmailAlreadyRegisteredError()

    # Argon2 is CPU heavy, so it runs in a thread to keep the event loop free.
    password_hash = await asyncio.to_thread(hash_password, data.password)
    user = User(
        first_name=data.first_name,
        last_name=data.last_name,
        email=data.email,
        password_hash=password_hash,
    )
    db.add(user)
    try:
        await db.commit()
    except IntegrityError:
        # Lost a race with a concurrent signup: the unique index is the real guard.
        await db.rollback()
        logger.warning(
            "signup_rejected",
            extra={"reason": "email_taken_race", "email": mask_email(data.email)},
        )
        raise EmailAlreadyRegisteredError() from None
    await db.refresh(user)  # loads id and created_at generated by the database
    logger.info("signup_ok", extra={"user_id": str(user.id)})
    return user


async def login(db: AsyncSession, data: LoginRequest) -> Token:
    user = await _get_by_email(db, data.email)
    # Also runs for an unknown user (hash=None) so timing can't reveal real emails.
    ok = await asyncio.to_thread(
        verify_password, data.password, user.password_hash if user else None
    )
    if not user or not ok:
        reason = "unknown_email" if not user else "bad_password"
        logger.warning(
            "login_failed", extra={"reason": reason, "email": mask_email(data.email)}
        )
        raise InvalidCredentialsError()

    logger.info("login_ok", extra={"user_id": str(user.id)})
    return Token(
        access_token=create_access_token(user.id),
        expires_in=get_settings().access_token_expire_minutes * 60,
    )
